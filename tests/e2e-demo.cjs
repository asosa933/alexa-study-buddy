const puppeteer = require('puppeteer-core'); const fs = require('fs'); const path = require('path');
const APP = process.argv[2] || 'http://localhost:8765/?mute&fast';
const DIR = '/workspace/eseguitore_lavori/alexa-study-buddy/docs'; const FR = '/workspace/eseguitore_lavori/gt-tools/asb_frames';
const VIDEO = !process.argv.includes('--novideo');
const assert = (c, m) => { if (!c) throw new Error('FAIL: ' + m); console.log('PASS:', m); };
(async () => {
  fs.rmSync(FR, { recursive: true, force: true }); fs.mkdirSync(FR, { recursive: true });
  const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox','--no-proxy-server'] });
  const p = await b.newPage(); await p.setViewport({ width: 1440, height: 900 });
  let errs = 0; p.on('pageerror', (e) => { console.log('PAGEERROR', e.message); errs++; });
  await p.goto(APP); await p.evaluate(() => localStorage.clear()); await p.reload(); await p.waitForSelector('#chips button');
  let f = 0;
  const cap = (t) => p.evaluate((t) => { let c = document.getElementById('__cap'); if (!c) { c = document.createElement('div'); c.id = '__cap'; c.style.cssText = 'position:fixed;left:50%;bottom:22px;transform:translateX(-50%);background:rgba(2,6,23,.92);color:#fff;font:600 22px system-ui;padding:12px 22px;border-radius:10px;z-index:9999;max-width:88%;text-align:center;border:1px solid #38bdf8'; document.body.append(c); } c.textContent = t; c.style.display = t ? 'block' : 'none'; }, t);
  const hold = async (s) => { if (!VIDEO) return; for (let i = 0; i < s * 4; i++) await p.screenshot({ path: path.join(FR, String(f++).padStart(5, '0') + '.png') }); };
  const say = async (txt, secs = 4) => { await p.click('#utter'); await p.type('#utter', txt, { delay: VIDEO ? 35 : 0 }); await hold(0.6); await p.click('#send'); await hold(secs); };
  const last = () => p.$$eval('.msg.alexa', (e) => e.at(-1).textContent);
  const expected = () => p.evaluate(() => { const q = window.__buddy.state.quiz; return q.queue[q.i].a[0]; });
  const shot = async (n) => { const c = await p.$('#__cap'); await cap(''); await p.screenshot({ path: `${DIR}/${n}.png` }); };

  await cap('Alexa Study Buddy: a simulated Alexa+ study companion that remembers your mistakes'); await hold(5);
  await cap('First visit: Alexa greets you and suggests what to say'); await hold(3);
  await cap('You say how much time you have, and the agent plans the session');
  await say('Alexa, my name is Alessio', 3);
  await say('I have an hour to study English', 6);
  assert(/2 focus blocks of 25 minutes/.test(await last()), 'plan for 60 min');
  await shot('01-plan');
  await cap('“Yes” runs two tool calls: a warm-up quiz and the first focus timer');
  await say('yes', 5);
  assert(/Question 1 of 5/.test(await last()) && await p.$eval('#timerChip', (e) => !e.hidden), 'quiz + timer started');
  await cap('Answer by voice or by typing. Small speech/typing slips are forgiven');
  const e1 = await expected(); await say(e1.length > 5 ? e1.slice(0, -2) + e1.at(-1) : e1, 4);
  await shot('02-quiz');
  await cap('Wrong answers are saved for spaced-repetition review'); await say('goed', 4);
  assert(/Not quite/.test(await last()), 'wrong answer handled');
  await say(await expected(), 3); await cap('“I don’t know” reveals the answer'); await say("I don't know", 4);
  await say(await expected(), 5);
  assert(/out of 5/.test(await last()), 'quiz finished');
  await shot('03-score');
  await cap('Every step is a real MCP-shaped tools/call, shown in the Agent trace'); await hold(5);
  const traces = await p.$$eval('#trace div', (e) => e.length); assert(traces >= 8, 'trace has tool calls: ' + traces);
  await cap('When the focus timer ends, Alexa speaks first (demo speed: 1 min = 2 s)');
  await p.waitForFunction(() => /Time's up/.test(document.getElementById('caption').textContent), { timeout: 70000, polling: 500 }).catch(() => {});
  // video: show the "time's up" moment
  await hold(5);
  assert(/Time's up/.test(await last()), 'proactive timer-done prompt');
  await shot('04-timer-done');
  await cap('Say yes, and it quizzes you on exactly the cards you missed'); await say('yes', 4);
  assert(/review the cards you missed/.test(await last()), 'review of missed cards');
  for (let i = 0; i < 3 && await p.evaluate(() => !!window.__buddy.state.quiz); i++) await say(await expected(), 2.5);
  await cap('Teach it your own words, and chain requests in one sentence');
  await say('remember that ubiquitous means everywhere then quiz me on my words', 5);
  assert(/ubiquitous\?/.test(await last()), 'chained add_card + quiz');
  await say('everywhere', 4);
  await cap('Ask for progress at any time: streak, minutes, weak spots'); await say('how am I doing?', 6);
  assert(/streak/.test(await last()), 'progress');
  await shot('05-progress');
  await cap('Reload tomorrow: memory persists, and Alexa opens with your due reviews');
  await p.evaluate(() => { const k = 'asb.memory.v1'; const d = JSON.parse(localStorage.getItem(k)); for (const c of Object.values(d.cards)) c.due -= 3 * 86400000; localStorage.setItem(k, JSON.stringify(d)); });
  await p.reload(); await p.waitForSelector('#chips button'); await hold(6);
  assert(/Welcome back, Alessio\. You have \d+ cards? to review/.test(await last()), 'proactive greeting after reload');
  await shot('06-welcome-back');
  await cap('Free and private: no account, no API key, runs 100% in the browser. Open source (MIT)'); await hold(5);
  await cap(''); await p.setViewport({ width: 390, height: 844, isMobile: true }); await p.reload(); await p.waitForSelector('#chips button'); await p.screenshot({ path: `${DIR}/07-mobile.png`, fullPage: false });
  assert(errs === 0, 'no page errors'); await b.close(); console.log('frames', f);
})().catch((e) => { console.error(e); process.exit(1); });
